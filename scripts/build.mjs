// Builds index.html and prompts/*.md from lenses.json and src/. No dependencies: `node scripts/build.mjs`.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import vm from "node:vm";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const read = (p) => readFileSync(join(root, p), "utf8");
const write = (p, s) => { mkdirSync(dirname(join(root, p)), { recursive: true }); writeFileSync(join(root, p), s); };

const data = JSON.parse(read("lenses.json"));
const coreSrc = read("src/core.js");
const ctx = {}; vm.createContext(ctx); vm.runInContext(coreSrc + "\nthis.CORE = CORE;", ctx);
const CORE = ctx.CORE;

// 1. index.html: inline data and core so the page stays a single dependency-free file
const json = JSON.stringify(data).replace(/</g, "\\u003c");
const html = read("src/index.template.html")
  .replace("/*@@DATA@@*/", () => json)
  .replace("/*@@CORE@@*/", () => coreSrc.trim());
write("index.html", "<!-- Generated by scripts/build.mjs from src/ and lenses.json. Edit those, then rebuild. -->\n" + html);

// 2. prompts
const site = (lang, medium) => `https://pairclear.com/${lang}/?utm_source=github&utm_medium=${medium}&utm_campaign=psychology-lenses`;
const tool = (lang, lens) => `https://pairclear.github.io/psychology-lenses/?lang=${lang}` + (lens ? `&lens=${lens}` : "");
const W = {
  en: {
    one: (n) => `# ${n} lens: a prompt for ChatGPT, Claude and other chats`,
    all: "# All psychology lenses: a prompt for ChatGPT, Claude and other chats",
    how: "Copy everything inside the box below and paste it into a new chat. Then describe a situation from your relationships: what happened, who said or did what, what you felt.",
    howAll: "Copy everything inside the box below and paste it into a new chat. The chat will ask for your situation, suggest two or three fitting lenses and compare how each would read it.",
    tool: (u) => `Prefer to work on your own first? Open the [web tool](${u}): it runs in your browser, and its "Prompt" button copies this prompt together with your situation and answers.`,
    warn: "> Education and self-reflection, not diagnosis or therapy. The prompt tells the chat not to label you or anyone else. Think about whether you want to share personal things with the service you paste this into. If you are in danger or thinking about hurting yourself, contact emergency services (112 / 911) or a helpline at [findahelpline.com](https://findahelpline.com).",
    foot: (u) => `Written with AI assistance and checked against the sources in [lenses.json](../../lenses.json). Text licence: CC BY 4.0. Made by [PairClear](${u}).`,
    other: "Other lenses",
    index: "# Prompts in English",
    indexP: "One prompt per school of psychology, plus one that compares them. Each prompt explains how a school would read your situation and never diagnoses or labels anyone.",
    allName: "All lenses, compared"
  },
  ru: {
    one: (n) => `# Линза «${n}»: промпт для ChatGPT, Claude и других чатов`,
    all: "# Все психологические линзы: промпт для ChatGPT, Claude и других чатов",
    how: "Скопируй всё, что в рамке ниже, и вставь в новый чат. Потом опиши ситуацию из своих отношений: что произошло, кто что сказал или сделал, что ты почувствовал(а).",
    howAll: "Скопируй всё, что в рамке ниже, и вставь в новый чат. Чат спросит о ситуации, предложит две-три подходящие линзы и сравнит, как каждая её прочитала бы.",
    tool: (u) => `Хочешь сначала подумать самостоятельно? Открой [веб-инструмент](${u}): он работает в браузере, а кнопка «Промпт» копирует этот промпт вместе с твоей ситуацией и ответами.`,
    warn: "> Просвещение и саморефлексия, а не диагностика и не терапия. Промпт запрещает чату навешивать ярлыки на тебя и других. Подумай, хочешь ли ты делиться личным с сервисом, куда вставляешь текст. Если тебе угрожает опасность или есть мысли навредить себе, обратись в экстренную службу (112) или на линию помощи на [findahelpline.com](https://findahelpline.com).",
    foot: (u) => `Написано с помощью ИИ и сверено с источниками из [lenses.json](../../lenses.json). Лицензия текста: CC BY 4.0. Сделано [PairClear](${u}).`,
    other: "Другие линзы",
    index: "# Промпты на русском",
    indexP: "По одному промпту на каждую школу психологии и один, который их сравнивает. Каждый объясняет, как школа прочитала бы твою ситуацию, и никогда не ставит диагнозов и не навешивает ярлыков.",
    allName: "Все линзы сразу, со сравнением"
  }
};

for (const lang of ["en", "ru"]) {
  const w = W[lang];
  const box = (s) => "```text\n" + s + "\n```";
  const others = (cur) => "## " + w.other + "\n\n" + data.lenses.filter(l => l.id !== cur).map(l => `- [${l[lang].name}](${l.id}.md)`).join("\n") + (cur ? `\n- [${w.allName}](all-lenses.md)` : "");
  for (const l of data.lenses) {
    const p = CORE.lensPrompt(l, lang, {});
    write(`prompts/${lang}/${l.id}.md`, [w.one(l[lang].name), "", w.how, "", w.tool(tool(lang, l.id)), "", w.warn, "", "---", "", box(p), "", "---", "", others(l.id), "", w.foot(site(lang, "readme")), ""].join("\n"));
  }
  const all = CORE.multiPrompt(data.lenses, lang, { suggest: true });
  write(`prompts/${lang}/all-lenses.md`, [w.all, "", w.howAll, "", w.tool(tool(lang)), "", w.warn, "", "---", "", box(all), "", "---", "", others(null), "", w.foot(site(lang, "readme")), ""].join("\n"));
  write(`prompts/${lang}/README.md`, [w.index, "", w.indexP, "", `- [${w.allName}](all-lenses.md)`, ...data.lenses.map(l => `- [${l[lang].name}](${l.id}.md): ${l[lang].looks_at}`), ""].join("\n"));
}

console.log("Built index.html and prompts for", data.lenses.length, "lenses");
